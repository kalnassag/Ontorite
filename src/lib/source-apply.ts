/**
 * Applying edited Turtle (the Source view) back to an ontology.
 *
 * The model stays the source of truth: the text is parsed (strictly) and
 * reconciled into the current ontology rather than replacing it.
 *  - Entities are matched by IRI, so IDs — and with them open cards and
 *    selections — survive.
 *  - An entity whose content didn't change keeps its exact object (same
 *    reference, same blank-node labels, same `dcterms:modified`).
 *  - Changed entities get a fresh `dcterms:modified`; new ones are stamped as
 *    created now unless the text says otherwise.
 *
 * Formatting and `#` comments in the text are not part of the RDF and are not
 * kept — the text is regenerated by the serializer after applying.
 */

import type { ExtraTriple, Individual, Ontology, OntologyClass, OntologyProperty, UnmappedTriple } from "../types";
import { parseTurtle } from "./turtle-parser";
import { buildModelFromTriples } from "./model-builder";
import { freshenTriples } from "./raw-triples";
import { STANDARD_PREFIXES } from "./uri-utils";

export interface EntityChanges {
  added: string[];
  changed: string[];
  removed: string[];
}

export interface ApplySummary {
  classes: EntityChanges;
  properties: EntityChanges;
  individuals: EntityChanges;
  /** The ontology header, prefixes or other statements changed */
  otherChanged: boolean;
}

export type ApplyResult =
  | { ok: true; next: Ontology; summary: ApplySummary; unchanged: boolean }
  | { ok: false; error: string; line?: number };

type Entity = OntologyClass | OntologyProperty | Individual;

const label = (e: Entity) =>
  ("labels" in e && e.labels[0]?.value) || e.localName || e.uri;

/**
 * Content fingerprint for change detection: ignores id and timestamps, the
 * order of multi-valued fields (the serializer regroups them), and blank-node
 * labels (they're renumbered on every export).
 */
function fingerprint(entity: Entity): string {
  const { id: _id, created: _c, modified: _m, ...content } = entity;
  return stableJson(content);
}

function stableJson(value: unknown): string {
  if (typeof value === "string") return JSON.stringify(value.startsWith("_:") ? "_:" : value);
  if (Array.isArray(value)) return `[${value.map(stableJson).sort().join(",")}]`;
  if (value && typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>)
      .filter(([, v]) => v !== undefined)
      .sort(([a], [b]) => a.localeCompare(b));
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${stableJson(v)}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

/** References a blank node it doesn't own (shared with another statement)? */
const referencesSharedBlankNode = (entity: Entity): boolean => {
  const extras: ExtraTriple[] = "extraTriples" in entity ? entity.extraTriples : [];
  if (extras.some((et) => !et.isLiteral && et.object.startsWith("_:") && !et.blankNodeTriples?.length)) return true;
  if ("propertyValues" in entity) {
    return entity.propertyValues.some((pv) => !pv.isLiteral && pv.value.startsWith("_:"))
      || entity.typeUris.some((t) => t.startsWith("_:"));
  }
  return false;
};

function hasSharedReferences(model: { metadata: { extraTriples: ExtraTriple[] }; classes: Entity[]; properties: Entity[]; individuals: Entity[] }): boolean {
  const sharedExtra = (extras: ExtraTriple[]) =>
    extras.some((et) => !et.isLiteral && et.object.startsWith("_:") && !et.blankNodeTriples?.length);
  return sharedExtra(model.metadata.extraTriples)
    || [...model.classes, ...model.properties, ...model.individuals].some(referencesSharedBlankNode);
}

/** Give every blank node in the parsed side fresh labels (one shared map, so links stay intact). */
function freshenParsed(model: ReturnType<typeof buildModelFromTriples>) {
  const labels = new Map<string, string>();
  const freshTerm = (term: string) =>
    term.startsWith("_:") ? freshenTriples([{ subject: term, predicate: "", object: "", isLiteral: true }], labels)[0]!.subject : term;
  const freshExtras = (extras: ExtraTriple[]): ExtraTriple[] => extras.map((et) => ({
    ...et,
    object: et.isLiteral ? et.object : freshTerm(et.object),
    blankNodeTriples: et.blankNodeTriples && freshenTriples(et.blankNodeTriples, labels),
  }));
  return {
    ...model,
    metadata: { ...model.metadata, extraTriples: freshExtras(model.metadata.extraTriples) },
    classes: model.classes.map((c) => ({ ...c, extraTriples: freshExtras(c.extraTriples) })),
    properties: model.properties.map((p) => ({ ...p, extraTriples: freshExtras(p.extraTriples) })),
    individuals: model.individuals.map((i) => ({
      ...i,
      typeUris: i.typeUris.map(freshTerm),
      propertyValues: i.propertyValues.map((pv) => (pv.isLiteral ? pv : { ...pv, value: freshTerm(pv.value) })),
    })),
    unmappedTriples: freshenTriples(model.unmappedTriples, labels) as UnmappedTriple[],
  };
}

function reconcile<T extends Entity>(current: T[], parsed: T[], now: string): { list: T[]; changes: EntityChanges } {
  const byUri = new Map(current.map((e) => [e.uri, e]));
  const changes: EntityChanges = { added: [], changed: [], removed: [] };
  const seen = new Set<string>();
  const list = parsed.map((incoming) => {
    seen.add(incoming.uri);
    const existing = byUri.get(incoming.uri);
    if (!existing) {
      changes.added.push(label(incoming));
      return { ...incoming, created: incoming.created ?? now, modified: incoming.modified ?? now };
    }
    // Unchanged: keep the stored object as-is (referential equality → no re-render, same labels)
    const same = fingerprint(existing) === fingerprint(incoming);
    if (same && !referencesSharedBlankNode(existing)) return existing;
    if (!same) changes.changed.push(label(incoming));
    // Same content but relinked to a shared blank node: keep its timestamp.
    // Otherwise an edited dcterms:modified in the text wins, else stamp the change now.
    const modifiedEdited = incoming.modified !== undefined && incoming.modified !== existing.modified;
    return {
      ...incoming,
      id: existing.id,
      created: incoming.created ?? existing.created,
      modified: same ? existing.modified : modifiedEdited ? incoming.modified : now,
    };
  });
  for (const e of current) if (!seen.has(e.uri)) changes.removed.push(label(e));
  return { list, changes };
}

/** Parse edited Turtle and reconcile it into `current`. Never mutates `current`. */
export function applyTurtleSource(text: string, current: Ontology): ApplyResult {
  const parsed = parseTurtle(text);
  if (parsed.errors.length > 0) {
    const err = parsed.errors[0]!;
    return { ok: false, error: err.line ? `Line ${err.line}: ${err.message}` : err.message, line: err.line };
  }
  const model = freshenParsed(buildModelFromTriples(parsed));
  const now = new Date().toISOString();

  const classes = reconcile(current.classes, model.classes, now);
  const properties = reconcile(current.properties, model.properties, now);
  const individuals = reconcile(current.individuals, model.individuals, now);

  const metadata = {
    ...model.metadata,
    // Not expressed in the text: keep the ontology's own settings
    baseUri: parsed.baseUri || parsed.prefixes[""] || current.metadata.baseUri,
    defaultLanguage: current.metadata.defaultLanguage,
    ontologyLabel: model.metadata.ontologyLabel || current.metadata.ontologyLabel,
    prefixes: { ...STANDARD_PREFIXES, ...model.metadata.prefixes },
  };
  const { modified: _cm, created: _cc, ...curMetaRest } = current.metadata;
  const { modified: _nm, created: _nc, ...nextMetaRest } = metadata;
  const otherChanged =
    stableJson(curMetaRest) !== stableJson(nextMetaRest) ||
    stableJson(current.unmappedTriples) !== stableJson(model.unmappedTriples);

  const summary: ApplySummary = {
    classes: classes.changes,
    properties: properties.changes,
    individuals: individuals.changes,
    otherChanged,
  };
  const unchanged = !otherChanged && [classes, properties, individuals].every(
    ({ changes: c }) => c.added.length + c.changed.length + c.removed.length === 0);
  if (unchanged) return { ok: true, next: current, summary, unchanged: true };

  return {
    ok: true,
    unchanged: false,
    summary,
    next: {
      ...current,
      metadata: { ...metadata, created: metadata.created ?? current.metadata.created, modified: now },
      classes: classes.list,
      properties: properties.list,
      individuals: individuals.list,
      // Keep the stored statements when they're unchanged, so their blank-node labels stay
      // put — unless something references a shared blank node, whose label must then
      // match the freshly parsed side
      unmappedTriples: otherChanged || hasSharedReferences(model) ? model.unmappedTriples : current.unmappedTriples,
      updatedAt: now,
    },
  };
}

/** "2 classes added, 1 property changed, 1 class removed" */
export function describeSummary(summary: ApplySummary): string {
  const parts: string[] = [];
  const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);
  for (const [changes, one, many] of [
    [summary.classes, "class", "classes"],
    [summary.properties, "property", "properties"],
    [summary.individuals, "individual", "individuals"],
  ] as const) {
    if (changes.added.length) parts.push(`${changes.added.length} ${plural(changes.added.length, one, many)} added`);
    if (changes.changed.length) parts.push(`${changes.changed.length} ${plural(changes.changed.length, one, many)} changed`);
    if (changes.removed.length) parts.push(`${changes.removed.length} ${plural(changes.removed.length, one, many)} removed`);
  }
  if (summary.otherChanged) parts.push("header / other statements changed");
  return parts.length > 0 ? parts.join(", ") : "No changes";
}
